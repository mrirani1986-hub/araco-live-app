def set_language(lang: str):
    global _lang
    _lang = "en" if lang == "en" else "ar"


def language() -> str:
    return _lang


def is_rtl() -> bool:
    return _lang == "ar"


def tr(key: str, **params) -> str:
    pair = STRINGS.get(key)
    if pair is None:
        text = key
    else:
        text = pair[0] if _lang == "ar" else pair[1]
    if params:
        try:
            text = text.format(**params)
        except (KeyError, IndexError):
            pass
    return text


def tr_error(err) -> str:
    """Translate a ValidationError entry: 'key' or ('key', {params})."""
    if isinstance(err, (tuple, list)):
        key, params = err[0], (err[1] if len(err) > 1 else {})
        return tr(key, **params)
    return tr(err)


def tr_status(status: str) -> str:
    return tr(f"status_{status}") if status else ""
